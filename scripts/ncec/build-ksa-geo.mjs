// One-off: bakes Saudi Arabia and its neighbours from Natural Earth 1:50m country borders
// (npm world-atlas, public domain data) into static SVG paths for the NCEC map, so the app
// ships no geo dependency and fetches nothing at runtime. Output: src/components/ncec/ksa-geo.ts.
// Usage: npm install --no-save --prefix <dir> world-atlas@2.0.2 topojson-client@3.1.0
//        node scripts/ncec/build-ksa-geo.mjs --from <dir>
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const from = process.argv[process.argv.indexOf("--from") + 1];
if (!from || from === "--from") throw new Error("--from <dir containing node_modules> is required");
const req = createRequire(path.resolve(from, "package.json"));
const topojson = req("topojson-client");
const world = JSON.parse(fs.readFileSync(req.resolve("world-atlas/countries-50m.json"), "utf8"));

// view window and projection (equirectangular, x scaled by cos of the mid latitude)
const VIEW = { lngMin: 34, lngMax: 56.6, latMin: 15.6, latMax: 32.6 };
const W = 640;
const K = Math.cos(((VIEW.latMin + VIEW.latMax) / 2) * (Math.PI / 180));
const SCALE = W / ((VIEW.lngMax - VIEW.lngMin) * K);
const H = Math.round((VIEW.latMax - VIEW.latMin) * SCALE);
const project = ([lng, lat]) => [(lng - VIEW.lngMin) * K * SCALE, (VIEW.latMax - lat) * SCALE];

const KSA = "682";
const NEIGHBOURS = ["400", "368", "414", "048", "634", "784", "512", "887", "818", "729", "232", "376", "275", "760", "364", "262", "231"];

const countries = topojson.feature(world, world.objects.countries).features;
function pathOf(feature) {
  const polys = feature.geometry.type === "Polygon" ? [feature.geometry.coordinates] : feature.geometry.coordinates;
  let d = "";
  for (const poly of polys) {
    for (const ring of poly) {
      let last = null;
      const pts = [];
      for (const c of ring) {
        const [x, y] = project(c);
        if (last && Math.hypot(x - last[0], y - last[1]) < 0.7) continue;
        pts.push([x, y]);
        last = [x, y];
      }
      if (pts.length < 3) continue;
      // skip rings entirely outside the window (with margin)
      if (pts.every(([x]) => x < -60 || x > W + 60) || pts.every(([, y]) => y < -60 || y > H + 60)) continue;
      d += "M" + pts.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join("L") + "Z";
    }
  }
  return d;
}

const ksa = countries.find((f) => f.id === KSA);
const neighbours = countries.filter((f) => NEIGHBOURS.includes(f.id)).map(pathOf).filter(Boolean);
const out = `// Generated by scripts/ncec/build-ksa-geo.mjs from Natural Earth 1:50m country borders
// (world-atlas 2.0.2, public domain). Do not edit by hand.
export const KSA_GEO = {
  width: ${W},
  height: ${H},
  view: ${JSON.stringify(VIEW)},
  k: ${K},
  scale: ${SCALE},
  ksa: ${JSON.stringify(pathOf(ksa))},
  neighbours: ${JSON.stringify(neighbours)},
} as const;

/** Projects a WGS84 point into the same SVG space as the paths above. */
export function projectKsa(lat: number, lng: number): { x: number; y: number } {
  return {
    x: (lng - KSA_GEO.view.lngMin) * KSA_GEO.k * KSA_GEO.scale,
    y: (KSA_GEO.view.latMax - lat) * KSA_GEO.scale,
  };
}
`;
fs.writeFileSync(path.resolve("src/components/ncec/ksa-geo.ts"), out);
console.log(`wrote src/components/ncec/ksa-geo.ts (${W}x${H}, ${(out.length / 1024).toFixed(1)} KB, ${neighbours.length} neighbours)`);
