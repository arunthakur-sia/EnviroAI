#!/usr/bin/env python3
"""Exports a seeded SQLite database (default ./data/nexus.db) as Postgres SQL
files for Supabase's SQL editor: 00_schema.sql, 01_data_NN.sql, 02_indexes.sql.
Usage: python3 -I scripts/export-postgres.py [db] [outdir]
Skips FTS virtual tables, triggers and foreign keys (see supabase/README.md)."""
import math, os, sqlite3, sys

db = sys.argv[1] if len(sys.argv) > 1 else "data/nexus.db"
out = sys.argv[2] if len(sys.argv) > 2 else "supabase"
MAX_FILE = 900_000   # bytes per data file, comfortable for the SQL editor
BATCH_ROWS = 200
# Files after this many are written in smaller pieces (the editor rejected a
# 1 MB file), so a partly loaded database can be resumed without redoing 1..N.
RESUME_AFTER = int(os.environ.get("RESUME_AFTER", "0"))
SMALL_FILE, SMALL_ROWS = 450_000, 40
os.makedirs(out, exist_ok=True)
for f in os.listdir(out):
    if f.endswith(".sql") and not f.startswith("03_"):
        os.remove(os.path.join(out, f))

con = sqlite3.connect(db)
con.text_factory = lambda b: b.decode("utf-8", "replace")
q = lambda s: '"' + s.replace('"', '""') + '"'

def pgtype(t):
    t = (t or "").upper()
    if "INT" in t: return "bigint"
    if "REAL" in t or "FLOA" in t or "DOUB" in t: return "double precision"
    if "BLOB" in t: return "bytea"
    return "text"

def lit(v, t):
    if v is None: return "NULL"
    if t == "bytea": return "'\\x" + bytes(v).hex() + "'"
    if t == "bigint":
        if isinstance(v, str):
            try: v = int(float(v))
            except ValueError: raise ValueError(f"non-numeric {v!r} in integer column")
        return str(int(v))
    if t == "double precision":
        v = float(v)
        return "NULL" if math.isnan(v) or math.isinf(v) else repr(v)
    if isinstance(v, bytes): v = v.decode("utf-8", "replace")
    return "'" + str(v).replace("\x00", "").replace("'", "''") + "'"

rows = con.execute("select name,type from sqlite_master where type in ('table','view') "
                   "and name not like 'sqlite\\_%' escape '\\' and name not like '\\_%' escape '\\' "
                   "and name not like '%\\_fts' escape '\\' and name not like '%\\_fts\\_%' escape '\\' order by name").fetchall()
tables = [n for n, t in rows if t == "table"]
views = [(n, s) for n, t in rows if t == "view" for s in [con.execute("select sql from sqlite_master where name=?", (n,)).fetchone()[0]]]

schema, indexes, coltypes = ["-- EnviroAI schema for Postgres (generated by scripts/export-postgres.py)\n"], [], {}
for t in tables:
    cols = con.execute(f"pragma table_info({q(t)})").fetchall()
    pk = sorted([c for c in cols if c[5]], key=lambda c: c[5])
    lines, types = [], []
    for cid, name, ty, notnull, dflt, pkpos in cols:
        p = pgtype(ty); types.append(p)
        l = f"  {q(name)} {p}"
        if dflt is not None and p != "bytea": l += f" DEFAULT {dflt}"
        if notnull or (len(pk) == 1 and pkpos): l += " NOT NULL"
        lines.append(l)
    if pk: lines.append("  PRIMARY KEY (" + ", ".join(q(c[1]) for c in pk) + ")")
    coltypes[t] = (cols, types)
    schema.append(f"DROP TABLE IF EXISTS {q(t)} CASCADE;\nCREATE TABLE {q(t)} (\n" + ",\n".join(lines) + "\n);\n")
    for _, iname, uniq, origin, _ in con.execute(f"pragma index_list({q(t)})").fetchall():
        if origin == "pk": continue
        ic = con.execute(f"pragma index_info({q(iname)})").fetchall()
        if any(c[2] is None for c in ic): continue  # expression index
        sql = con.execute("select sql from sqlite_master where name=?", (iname,)).fetchone()
        if sql and sql[0] and " WHERE " in sql[0].upper(): continue  # partial index
        indexes.append(f"CREATE {'UNIQUE ' if uniq else ''}INDEX IF NOT EXISTS {q(iname)} ON {q(t)} ({', '.join(q(c[2]) for c in sorted(ic))});")
for n, s in views:
    schema.append(f"DROP VIEW IF EXISTS {q(n)};\n" + s.replace("`", '"').rstrip().rstrip(";") + ";\n")
open(f"{out}/00_schema.sql", "w").write("\n".join(schema))
open(f"{out}/02_indexes.sql", "w").write("-- Run after all 01_data files.\n" + "\n".join(indexes) + "\n")

# data
fileno, buf, size, counts = 0, [], 0, {}
def flush():
    global fileno, buf, size
    if not buf: return
    fileno += 1
    open(f"{out}/01_data_{fileno:02d}.sql", "w").write("".join(buf)); buf, size = [], 0
for t in tables:
    cols, types = coltypes[t]
    head = f"INSERT INTO {q(t)} ({', '.join(q(c[1]) for c in cols)}) VALUES\n"
    cur = con.execute(f"select * from {q(t)}"); n = 0
    while True:
        batch = cur.fetchmany(BATCH_ROWS)
        if not batch: break
        n += len(batch)
        build = lambda rs: head + ",\n".join("(" + ", ".join(lit(v, ty) for v, ty in zip(r, types)) + ")" for r in rs) + ";\n"
        def add(rs):
            global size
            if RESUME_AFTER and fileno >= RESUME_AFTER:
                for k in range(0, len(rs), SMALL_ROWS):
                    stmt = build(rs[k:k + SMALL_ROWS])
                    if size and size + len(stmt) > SMALL_FILE: flush()
                    buf.append(stmt); size += len(stmt)
                return
            stmt = build(rs)
            if size and size + len(stmt) > MAX_FILE:
                flush()
                if RESUME_AFTER and fileno >= RESUME_AFTER: return add(rs)
            buf.append(stmt); size += len(stmt)
        add(batch)
    counts[t] = n
flush()
print(f"{len(tables)} tables, {sum(counts.values())} rows, {fileno} data files")
