/** "19 September 2026" / "19 سبتمبر 2026" (Western digits in both). */
export function fmtDate(iso: string, lang: Lang): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso.slice(0, 10);
  try {
    return new Intl.DateTimeFormat(lang === "ar" ? "ar-QA-u-nu-latn" : "en-GB", {
      day: "numeric",
      month: "long",
      year: "numeric",
    }).format(d);
  } catch {
    return iso.slice(0, 10);
  }
}

/** XML and HTML escaping for the SVG builders. */
export const esc = (s: string): string =>
  String(s ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

/** Tone colours for tiles and callouts. */
export function toneColour(tone: "maroon" | "gulf" | "gold" | "ink" | undefined): string {
  switch (tone) {
    case "gulf":
      return C.gulf;
    case "gold":
      return C.gold;
    case "ink":
      return C.ink600;
    default:
      return C.maroon;
  }
}

export function toneTint(tone: "maroon" | "gulf" | "gold" | "ink" | undefined): string {
  switch (tone) {
    case "gulf":
      return C.gulf100;
    case "gold":
      return C.gold100;
    case "ink":
      return C.sand;
    default:
      return C.maroon100;
  }
}
