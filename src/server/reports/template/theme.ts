/** "19 September 2026" / "19 سبتمبر 2026" (Western digits in both). */
export function fmtDate(iso: string, lang: Lang): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso.slice(0, 10);
  try {
    return new Intl.DateTimeFormat(lang === "ar" ? "ar-SA-u-nu-latn" : "en-GB", {
      day: "numeric",
      month: "long",
      year: "numeric",
    }).format(d);
  } catch {
    return iso.slice(0, 10);
  }
}

/** XML and HTML escaping for the SVG builders. */
export const esc = (s: string): string =>
  String(s ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

/** Tone colours for tiles and callouts. */
export function toneColour(tone: "navy" | "teal" | "aqua" | "ink" | undefined): string {
  switch (tone) {
    case "teal":
      return C.teal;
    case "aqua":
      return C.aqua;
    case "ink":
      return C.ink600;
    default:
      return C.navy;
  }
}

export function toneTint(tone: "navy" | "teal" | "aqua" | "ink" | undefined): string {
  switch (tone) {
    case "teal":
      return C.teal100;
    case "aqua":
      return C.aqua100;
    case "ink":
      return C.mist;
    default:
      return C.navy100;
  }
}
