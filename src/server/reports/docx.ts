function itemTable(lang: Lang, items: ReportItem[], syntheses: Record<string, string>): Table {
  const t = L[lang];
  const title = (i: ReportItem) => (lang === "ar" ? i.titleAr || i.titleEn : i.titleEn);
  const meta = (i: ReportItem) => (lang === "ar" ? i.metaAr || i.metaEn : i.metaEn);
  const header = new TableRow({
    tableHeader: true,
    children: [
      shadedCell("#", lang, MAROON, { bold: true, color: WHITE, widthPct: 6 }),
      shadedCell(t.items, lang, MAROON, { bold: true, color: WHITE, widthPct: 34 }),
      shadedCell("", lang, MAROON, { bold: true, color: WHITE, widthPct: 60 }),
    ],
  });
  const rows = items.map((i, idx) => {
    const fill = idx % 2 === 0 ? WHITE : SAND;
    const synthesis = syntheses[i.id] ?? "";
    return new TableRow({
      children: [
        shadedCell(String(idx + 1), lang, fill, { widthPct: 6 }),
        new TableCell({
          shading: { type: ShadingType.CLEAR, fill },
          margins: { top: 90, bottom: 90, left: 120, right: 120 },
          children: [
            new Paragraph({
              bidirectional: lang === "ar",
              alignment: lang === "ar" ? AlignmentType.RIGHT : AlignmentType.LEFT,
              children: [
                new TextRun({
                  text: title(i),
                  font: bodyFont(lang),
                  size: 20,
                  bold: true,
                  color: INK,
                  rightToLeft: lang === "ar",
                }),
              ],
            }),
            new Paragraph({
              bidirectional: lang === "ar",
              alignment: lang === "ar" ? AlignmentType.RIGHT : AlignmentType.LEFT,
              children: [
                new TextRun({
                  text: [i.type, i.date?.slice(0, 10), meta(i)].filter(Boolean).join(" · "),
                  font: bodyFont(lang),
                  size: 17,
                  color: "5E5760",
                  rightToLeft: lang === "ar",
                }),
              ],
            }),
          ],
        }),
        shadedCell(synthesis, lang, fill, { widthPct: 60 }),
      ],
    });
  });
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    visuallyRightToLeft: lang === "ar",
    rows: [header, ...rows],
  });
}

/** Chart as a docx-native shaded bar table (label, bar, value). */
function chartTable(lang: Lang, chart: ReportChart): (Paragraph | Table)[] {
  const label = lang === "ar" ? chart.labelAr || chart.labelEn : chart.labelEn;
  const max = Math.max(...chart.points.map((p) => Math.abs(p.value)), chart.target ?? 0, 1);
  const rows = chart.points.slice(-8).map((p) => {
    const pct = Math.max(2, Math.round((Math.abs(p.value) / max) * 100));
    return new TableRow({
      children: [
        shadedCell(p.period, lang, WHITE, { widthPct: 16 }),
        new TableCell({
          width: { size: 64, type: WidthType.PERCENTAGE },
          margins: { top: 60, bottom: 60, left: 80, right: 80 },
          children: [
            new Table({
              width: { size: 100, type: WidthType.PERCENTAGE },
              borders: {
                top: { style: BorderStyle.NONE, size: 0, color: WHITE },
                bottom: { style: BorderStyle.NONE, size: 0, color: WHITE },
                left: { style: BorderStyle.NONE, size: 0, color: WHITE },
                right: { style: BorderStyle.NONE, size: 0, color: WHITE },
                insideVertical: { style: BorderStyle.NONE, size: 0, color: WHITE },
                insideHorizontal: { style: BorderStyle.NONE, size: 0, color: WHITE },
              },
              rows: [
                new TableRow({
                  children: [
                    new TableCell({
                      width: { size: pct, type: WidthType.PERCENTAGE },
                      shading: { type: ShadingType.CLEAR, fill: MAROON },
                      children: [new Paragraph({ children: [] })],
                    }),
                    new TableCell({
                      width: { size: 100 - pct, type: WidthType.PERCENTAGE },
                      shading: { type: ShadingType.CLEAR, fill: SAND },
                      children: [new Paragraph({ children: [] })],
                    }),
                  ],
                }),
              ],
            }),
          ],
        }),
        shadedCell(
          `${p.value}${chart.unit ? ` ${chart.unit}` : ""}`,
          lang,
          WHITE,
          { widthPct: 20 }
        ),
      ],
    });
  });
  return [
    para(lang, chart.target != null ? `${label} (${L[lang].target}: ${chart.target}${chart.unit ? ` ${chart.unit}` : ""})` : label, {
      bold: true,
      spacingAfter: 80,
    }),
    new Table({
      width: { size: 100, type: WidthType.PERCENTAGE },
      visuallyRightToLeft: lang === "ar",
      rows,
    }),
  ];
}

function pullQuote(lang: Lang, text: string): Table {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    visuallyRightToLeft: lang === "ar",
    rows: [
      new TableRow({
        children: [
          new TableCell({
            shading: { type: ShadingType.CLEAR, fill: SAND },
            margins: { top: 160, bottom: 160, left: 220, right: 220 },
            children: [
              new Paragraph({
                bidirectional: lang === "ar",
                alignment: lang === "ar" ? AlignmentType.RIGHT : AlignmentType.LEFT,
                children: [
                  new TextRun({
                    text,
                    font: bodyFont(lang),
                    size: 22,
                    italics: true,
                    color: MAROON_DARK,
                    rightToLeft: lang === "ar",
                  }),
                ],
              }),
            ],
          }),
        ],
      }),
    ],
  });
}

function languageSection(
  lang: Lang,
  narrative: ReportNarrative,
  items: ReportItem[],
  charts: ReportChart[],
  options: ReportOptionsInput,
  meta: { scopeLabel: string; dateLabel: string; classification: number; generatedAt: string },
  numberingRef: string
): ISectionOptions {
  const t = L[lang];
  const children: (Paragraph | Table | TableOfContents)[] = [];
  children.push(...coverSection(lang, { title: narrative.title, scopeLabel: meta.scopeLabel, dateLabel: meta.dateLabel, classification: meta.classification }));
  children.push(new Paragraph({ children: [], pageBreakBefore: true }));
  children.push(heading(lang, t.toc));
  children.push(
    new TableOfContents(t.toc, { hyperlink: true, headingStyleRange: "1-2" })
  );
  children.push(new Paragraph({ children: [], pageBreakBefore: true }));

  children.push(heading(lang, t.executive));
  for (const p of narrative.executive_summary) children.push(para(lang, p));

  children.push(heading(lang, t.findings));
  for (const f of narrative.key_findings) {
    children.push(
      new Paragraph({
        bidirectional: lang === "ar",
        alignment: lang === "ar" ? AlignmentType.RIGHT : AlignmentType.LEFT,
        numbering: { reference: numberingRef, level: 0 },
        spacing: { after: 100 },
        children: [
          new TextRun({
            text: f,
            font: bodyFont(lang),
            size: 22,
            color: INK,
            rightToLeft: lang === "ar",
          }),
        ],
      })
    );
  }

  if (narrative.implications.length) {
    children.push(heading(lang, t.implications));
    for (const imp of narrative.implications) {
      children.push(para(lang, `${imp.text}${imp.codes.length ? ` (${imp.codes.join(", ")})` : ""}`));
    }
  }

  if (narrative.actions.length) {
    children.push(heading(lang, t.actions));
    for (const a of narrative.actions) {
      children.push(para(lang, `${a.text} ${a.owner ? `(${t.owner}: ${a.owner})` : ""}`));
    }
  }

  if (charts.length) {
    children.push(heading(lang, t.charts));
    for (const c of charts) children.push(...chartTable(lang, c));
  }

  children.push(heading(lang, t.items));
  children.push(itemTable(lang, items, narrative.syntheses));

  // pull quotes for lessons in a sand box
  const lessonQuote = items.find((i) => i.type === "lesson");
  if (lessonQuote) {
    const text = lang === "ar" ? lessonQuote.textAr || lessonQuote.textEn : lessonQuote.textEn;
    if (text) {
      children.push(new Paragraph({ children: [], spacing: { after: 120 } }));
      children.push(pullQuote(lang, text.slice(0, 300)));
    }
  }

  if (narrative.assessment_note) {
    children.push(para(lang, narrative.assessment_note, { italics: true, size: 18, color: "5E5760", spacingAfter: 80 }));
  }

  if (options.includeSources) {
    children.push(heading(lang, t.sources));
    items.forEach((i, idx) => {
      children.push(
        para(
          lang,
          `${idx + 1}. ${lang === "ar" ? i.titleAr || i.titleEn : i.titleEn} (${i.type}${i.date ? `, ${i.date.slice(0, 10)}` : ""})`,
          { size: 18, spacingAfter: 40 }
        )
      );
    });
  }

  return {
    properties: {},
    headers: {
      default: new Header({
        children: [
          new Paragraph({
            bidirectional: lang === "ar",
            alignment: lang === "ar" ? AlignmentType.LEFT : AlignmentType.RIGHT,
            children: [
              new TextRun({
                text: narrative.title,
                font: bodyFont(lang),
                size: 16,
                color: "928B93",
                rightToLeft: lang === "ar",
              }),
            ],
          }),
        ],
      }),
    },
    footers: {
      default: new Footer({
        children: [
          new Paragraph({
            alignment: AlignmentType.CENTER,
            children: [
              new TextRun({
                text: `${t.classification[Math.min(3, Math.max(0, meta.classification - 1))]}  ·  ${meta.generatedAt}  ·  `,
                font: bodyFont(lang),
                size: 16,
                color: "928B93",
              }),
              new TextRun({
                children: [PageNumber.CURRENT],
                font: bodyFont(lang),
                size: 16,
                color: "928B93",
              }),
            ],
          }),
        ],
      }),
    },
    children: children as ISectionOptions["children"],
  };
}

export async function buildReportDocx(input: {
  parts: { lang: Lang; narrative: ReportNarrative }[];
  items: ReportItem[];
  charts: ReportChart[];
  scope: ReportScopeInput;
  options: ReportOptionsInput;
  classification: number;
  generatedAt: string;
}): Promise<Buffer> {
  const dateLabel = input.generatedAt.slice(0, 10);
  const sections = input.parts.map((part, idx) =>
    languageSection(
      part.lang,
      part.narrative,
      input.items,
      input.charts,
      input.options,
      {
        scopeLabel: part.lang === "ar" ? input.scope.labelAr || input.scope.labelEn : input.scope.labelEn,
        dateLabel,
        classification: input.classification,
        generatedAt: input.generatedAt.slice(0, 16).replace("T", " "),
      },
      `findings-${idx}`
    )
  );
  const doc = new Document({
    numbering: {
      config: input.parts.map((_, idx) => ({
        reference: `findings-${idx}`,
        levels: [
          {
            level: 0,
            format: LevelFormat.DECIMAL,
            text: "%1.",
            alignment: AlignmentType.START,
          },
        ],
      })),
    },
    features: { updateFields: true }, // the TOC field updates on open
    styles: {
      default: {
        heading1: {
          run: { font: HEAD_FONT, bold: true, color: MAROON },
        },
      },
    },
    sections,
  });
  return Buffer.from(await Packer.toBuffer(doc));
}
