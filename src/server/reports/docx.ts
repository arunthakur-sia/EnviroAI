      right: { style: BorderStyle.NONE, size: 0, color: WHITE },
      insideHorizontal: { style: BorderStyle.NONE, size: 0, color: WHITE },
      insideVertical: { style: BorderStyle.NONE, size: 0, color: WHITE },
