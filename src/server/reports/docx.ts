function bodyFont(lang: Lang): string {
  return lang === "ar" ? BODY_FONT_AR : BODY_FONT_EN;
}

function para(
  lang: Lang,
  text: string,
  opts: { bold?: boolean; size?: number; color?: string; italics?: boolean; spacingAfter?: number } = {}
): Paragraph {
  return new Paragraph({
    bidirectional: lang === "ar",
    alignment: lang === "ar" ? AlignmentType.RIGHT : AlignmentType.LEFT,
    spacing: { after: opts.spacingAfter ?? 160 },
    children: [
      new TextRun({
        text,
        font: bodyFont(lang),
        size: opts.size ?? 22, // 11pt
        bold: opts.bold,
        italics: opts.italics,
        color: opts.color ?? INK,
        rightToLeft: lang === "ar",
      }),
    ],
  });
}

/** Section heading with the navy side rule (a bordered paragraph). */
function heading(lang: Lang, text: string): Paragraph {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    bidirectional: lang === "ar",
    alignment: lang === "ar" ? AlignmentType.RIGHT : AlignmentType.LEFT,
    spacing: { before: 320, after: 160 },
    border:
      lang === "ar"
        ? { right: { style: BorderStyle.SINGLE, size: 24, color: MAROON, space: 6 } }
        : { left: { style: BorderStyle.SINGLE, size: 24, color: MAROON, space: 6 } },
    children: [
      new TextRun({
        text,
        font: HEAD_FONT,
        size: 30,
        bold: true,
        color: MAROON,
        rightToLeft: lang === "ar",
      }),
    ],
  });
}

function goldRule(): Paragraph {
  return new Paragraph({
    spacing: { after: 200 },
    border: { bottom: { style: BorderStyle.SINGLE, size: 8, color: GOLD, space: 1 } },
    children: [],
  });
}

function shadedCell(text: string, lang: Lang, fill: string, opts: { bold?: boolean; color?: string; widthPct?: number } = {}) {
  return new TableCell({
    shading: { type: ShadingType.CLEAR, fill },
    width: opts.widthPct ? { size: opts.widthPct, type: WidthType.PERCENTAGE } : undefined,
    margins: { top: 90, bottom: 90, left: 120, right: 120 },
    children: [
      new Paragraph({
        bidirectional: lang === "ar",
        alignment: lang === "ar" ? AlignmentType.RIGHT : AlignmentType.LEFT,
        children: [
          new TextRun({
            text,
            font: bodyFont(lang),
            size: 20,
            bold: opts.bold,
            color: opts.color ?? INK,
            rightToLeft: lang === "ar",
          }),
        ],
      }),
    ],
  });
}

